package dev.phptools.core.settings

/** Когда запускать проверку в редакторе. */
enum class CheckMode {
    /** При вводе: несохранённый буфер, если инструмент это умеет; иначе как [ON_SAVE]. */
    ON_TYPING,

    /** Только по сохранённому файлу; несохранённый ждёт сохранения. */
    ON_SAVE,

    /** В редакторе не запускать; только по команде пользователя (Inspect Code, панель инструмента). */
    MANUAL,
}
